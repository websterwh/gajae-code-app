const cell = (value) => String(value ?? 'unknown').replace(/\|/gu, '\\|');

const table = (headers, body) => [
  `| ${headers.join(' | ')} |`,
  `| ${headers.map(() => '---').join(' | ')} |`,
  ...body.map((row) => `| ${row.map(cell).join(' | ')} |`),
].join('\n');

const block = (lines) => ['```', ...lines, '```'].join('\n');

/**
 * Turn collected facts into the file an agent reads before touching the host.
 * Everything here is either observed or a rule that follows from an observation;
 * the generated part is meant to be regenerated, not hand-edited.
 */
export function renderAgentsMd(facts, { root = '/' } = {}) {
  const { system, init, packages, containers, resources, network, scheduled, security, timezone, quirks } = facts;
  const os = system.os ?? {};

  const sections = [
    `# AGENTS.md — ${system.hostname}`,
    '',
    '> Generated by `deploy/host/gajae-host.mjs` from read-only probes. Re-run',
    '> `node deploy/host/gajae-host.mjs agents-md` after the host changes;',
    `> hand edits below this line are overwritten. Collected ${facts.collectedAt}.`,
    '',
    '## What this machine is',
    '',
    table(['Field', 'Value'], [
      ['Hostname', system.hostname],
      ['OS', os.prettyName ?? os.name ?? 'unknown'],
      ['Distro ID / version', [os.id, os.version].filter(Boolean).join(' ') || 'unknown'],
      ['Kernel / arch', `${system.kernel} · ${system.arch}`],
      ['Platform', system.platform],
      ['Init', init.name ? `${init.name}${init.systemd ? ' (systemd)' : ''}` : 'unknown'],
      ['Package manager', packages.manager],
      ['Timezone', timezone],
      ['CPUs', resources.cpus],
      ['Memory', `${resources.memoryMB} MB`],
    ]),
    '',
    '## Containers',
    '',
  ];

  if (containers.runtime) {
    sections.push(`Docker ${containers.version} is the container runtime on this host.`, '');
    sections.push(containers.list.length
      ? table(['Name', 'Image', 'Status', 'Ports'], containers.list.map((container) => [container.name, container.image, container.status, container.ports || '—']))
      : 'No containers are currently running.');
  } else {
    sections.push('Docker is not installed on this host (or its daemon is not reachable by this user).');
    sections.push('Before assuming a container exists, check `docker ps`; before assuming a service runs on the host, ask the operator.');
  }
  sections.push('');

  sections.push('## Storage', '');
  sections.push(resources.disks.length
    ? table(['Filesystem', 'Size', 'Used', 'Avail', 'Use%', 'Mount'], resources.disks.map((disk) => [disk.filesystem, disk.size, disk.used, disk.avail, disk.percent, disk.mount]))
    : '`df` returned nothing; check `mount` before assuming a path is a separate disk.');
  sections.push('');

  sections.push('## Network', '');
  sections.push(network.addresses.length
    ? table(['Interface', 'Address'], network.addresses.map((entry) => [entry.iface, entry.address]))
    : 'No global IPv4 addresses were reported.');
  sections.push('');
  if (network.nameservers.length) sections.push(`Resolvers: ${network.nameservers.join(', ')}`, '');
  if (network.listeners.length) {
    sections.push('Listening sockets (as reported by the host, not the app container):', '');
    sections.push(block(network.listeners.map((listener) => `${listener.proto} ${listener.address}`)));
    sections.push('');
  }

  sections.push('## Scheduling', '');
  sections.push(scheduled.timers.length ? `Systemd timers:\n\n${block(scheduled.timers)}` : 'No systemd timers are readable on this host.');
  sections.push('');
  sections.push(scheduled.cron.length ? `Cron entries:\n\n${block(scheduled.cron)}` : 'No cron entries were readable for this user.');
  sections.push('');

  sections.push('## Host quirks', '');
  sections.push(quirks.length ? quirks.map((quirk) => `- ${quirk}`).join('\n') : '- Nothing unusual was detected by the probes.');
  sections.push('');

  sections.push(
    '## How to work on this host',
    '',
    '- The host is not the app container. Paths, installed tools and running processes differ; `docker exec` into the app for app work, host commands for host work.',
    '- Start read-only: `node deploy/host/gajae-host.mjs inventory` and `node deploy/host/gajae-host.mjs run host.info`.',
    '- Host operations go through the verb allow-list in `deploy/host/verbs.mjs`: a fixed command plus a validated container or service name. There is no shell verb, and there will not be one.',
    '- Mutating verbs (`docker.restart`, `service.restart`) are declared but not enabled. Do not work around that with `docker` or `service` directly; ask the operator.',
    '- Never prune, remove volumes, or restart the reverse proxy or DNS while diagnosing something else. Reversible, narrow actions first; state what you are about to change.',
    '',
    '## Verify (read-only)',
    '',
    block([
      `node ${root.replace(/\/+$/u, '')}/deploy/host/gajae-host.mjs run host.info`,
      `node ${root.replace(/\/+$/u, '')}/deploy/host/gajae-host.mjs run docker.ps`,
      `node ${root.replace(/\/+$/u, '')}/deploy/host/gajae-host.mjs run host.listeners`,
    ]),
    '',
  );

  if (security.lsm.length || security.cgroupV2) {
    sections.push(`## Kernel notes`, '', `- LSM: ${security.lsm.length ? security.lsm.join(', ') : 'none reported'}`);
    if (security.cgroupV2) sections.push('- cgroup v2 is in use.');
    sections.push('');
  }

  return `${sections.join('\n')}\n`;
}
